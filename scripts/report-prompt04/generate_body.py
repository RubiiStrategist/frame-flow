# ━━ Documento com TOC ━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
class TocDocTemplate(SimpleDocTemplate):
    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            # página exibida = página absoluta - 1 (Sumário é a página 'i')
            self.notify('TOCEntry', (level, text, max(1, self.page - 1), key))


def on_page(canvas, doc):
    canvas.saveState()
    # cabeçalho: título à esquerda + régua accent
    canvas.setFont('FreeSerif-Italic', 7.5)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawString(MARGIN, PAGE_H - 40, 'FRAME FLOW OS — Relatório do protótipo interativo · PROMPT 04')
    canvas.setStrokeColor(ACCENT)
    canvas.setLineWidth(1.2)
    canvas.line(MARGIN, PAGE_H - 46, PAGE_W - MARGIN, PAGE_H - 46)
    # rodapé: régua leve + número por zona (i para o Sumário; arábico para o corpo)
    canvas.setStrokeColor(BORDER)
    canvas.setLineWidth(0.5)
    canvas.line(MARGIN, 40, PAGE_W - MARGIN, 40)
    canvas.setFont('FreeSerif', 9)
    canvas.setFillColor(TEXT_MUTED)
    canvas.drawRightString(PAGE_W - MARGIN, 27, 'i' if doc.page == 1 else str(doc.page - 1))
    canvas.restoreState()


def safe_keep_together(elements):
    total_h = 0
    for el in elements:
        try:
            _, h = el.wrap(AVAIL_W, PAGE_H)
        except Exception:
            h = 0
        total_h += h
    if total_h <= MAX_KEEP:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)


def add_heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def embed_image(path, max_width, max_height):
    img = PILImage.open(path)
    ow, oh = img.size
    ratio = min(max_width / ow if ow > max_width else 1.0,
                max_height / oh if oh > max_height else 1.0)
    return Image(path, width=ow * ratio, height=oh * ratio)


def make_table(spec):
    ratios = spec['ratios']
    col_w = [r * AVAIL_W for r in ratios]
    assert abs(sum(col_w) - AVAIL_W) < 1.0, 'colWidths excedem a área útil'
    head = [Paragraph('<b>%s</b>' % h, S_TH) for h in spec['head']]
    rows = [[Paragraph(c, S_TD) for c in row] for row in spec['rows']]
    data = [head] + rows
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(('BACKGROUND', (0, i), (-1, i),
                      TABLE_ROW_ODD if i % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def make_callout(stats):
    """Barra única de 3 colunas (sem tabelas aninhadas) — centralizada por construção."""
    row_stats = [Paragraph('<b>%s</b>' % v, S_STAT) for v, _ in stats]
    row_labels = [Paragraph(l, S_STAT_LBL) for _, l in stats]
    third = AVAIL_W / 3.0
    t = Table([row_stats, row_labels], colWidths=[third] * 3, hAlign='CENTER')
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), CARD_BG),
        ('BOX', (0, 0), (-1, -1), 1, ACCENT),
        ('LINEBEFORE', (1, 0), (2, -1), 0.75, BORDER),
        ('TOPPADDING', (0, 0), (-1, 0), 10),
        ('BOTTOMPADDING', (0, 1), (-1, 1), 10),
        ('TOPPADDING', (0, 1), (-1, 1), 2),
        ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 8),
        ('RIGHTPADDING', (0, 0), (-1, -1), 8),
    ]))
    return [Spacer(1, 10), KeepTogether(t), Spacer(1, 14)]


def make_pair_figure(paths, caption):
    imgs = []
    col_w = AVAIL_W * 0.47
    for p in paths:
        imgs.append(embed_image(p, col_w, 295))
    t = Table([imgs], colWidths=[AVAIL_W * 0.5, AVAIL_W * 0.5], hAlign='CENTER')
    t.setStyle(TableStyle([
        ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 0),
        ('RIGHTPADDING', (0, 0), (-1, -1), 0),
    ]))
    cap = Paragraph(caption, S_CAPTION)
    return [Spacer(1, 14)] + safe_keep_together([t, Spacer(1, 8), cap]) + [Spacer(1, 12)]


def build_story():
    from report_content import BLOCO
    story = []
    toc = TableOfContents()
    toc.levelStyles = [S_TOC0]
    story.append(Paragraph('<b>Sumário</b>', S_TOC_TITLE))
    story.append(HRFlowable(width='100%', color=ACCENT, thickness=1.2, spaceAfter=12))
    story.append(toc)
    story.append(PageBreak())  # única quebra estrutural: Sumário → conteúdo

    chapter = 0
    i = 0
    while i < len(BLOCO):
        entry = BLOCO[i]
        kind = entry[0]
        payload = entry[1] if len(entry) == 2 else entry[1:]
        if kind == 'h1':
            chapter += 1
            h = add_heading('%d. %s' % (chapter, payload), S_H1, level=0)
            rule = HRFlowable(width='100%', color=ACCENT, thickness=1.2,
                              spaceBefore=0, spaceAfter=10)
            nxt = []
            if i + 1 < len(BLOCO):
                nk, np_ = BLOCO[i + 1]
                if nk == 'p':
                    nxt = [Paragraph(np_, S_BODY)]
                    i += 1
            story.append(CondPageBreak(AVAIL_H * 0.25))
            story.extend(safe_keep_together([h, rule] + nxt))
        elif kind == 'h2':
            story.append(CondPageBreak(60))
            story.append(Paragraph('<b>%s</b>' % payload, S_H2))
        elif kind == 'p':
            story.append(Paragraph(payload, S_BODY))
        elif kind == 'bullets':
            for b in payload:
                story.append(Paragraph(b, S_BULLET, bulletText='•'))
            story.append(Spacer(1, 6))
        elif kind == 'table':
            t = make_table(payload)
            cap = Paragraph(payload['caption'], S_CAPTION)
            story.append(Spacer(1, 10))
            if len(payload['rows']) <= 8:
                story.extend(safe_keep_together([t, Spacer(1, 6), cap]))
            else:
                story.append(t)
                story.append(Spacer(1, 6))
                story.append(cap)
            story.append(Spacer(1, 12))
        elif kind == 'figure':
            path, caption = payload
            img = embed_image(path, AVAIL_W * 0.92, 300)
            cap = Paragraph(caption, S_CAPTION)
            story.append(Spacer(1, 14))
            story.extend(safe_keep_together([img, Spacer(1, 8), cap]))
            story.append(Spacer(1, 12))
        elif kind == 'figures2':
            paths, caption = payload
            story.extend(make_pair_figure(paths, caption))
        elif kind == 'callout':
            story.extend(make_callout(payload))
        elif kind == 'note':
            story.append(Paragraph(payload, S_NOTE))
        i += 1
    return story


def main():
    out = os.path.join(BASE, 'body.pdf')
    doc = TocDocTemplate(
        out, pagesize=A4,
        leftMargin=MARGIN, rightMargin=MARGIN, topMargin=TOP_M, bottomMargin=BOT_M,
        title='FRAME FLOW OS — Relatório do Protótipo Interativo (PROMPT 04)',
        author='Z.ai', creator='Z.ai',
        subject='Consolidação da direção visual Conceito C — protótipo interativo, testes e plano de integração',
    )
    doc.multiBuild(build_story(), onFirstPage=on_page, onLaterPages=on_page)
    print('body.pdf gerado:', out)


if __name__ == '__main__':
    main()
